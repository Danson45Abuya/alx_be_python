# Prompt the user for their current age
current_age = int(input("How old are you? "))

# Calculate the number of years between 2023 and 2050
years_to_2050 = 2050 - 2023

# Calculate the user's age in 2050
age_in_2050 = current_age + years_to_2050

# Display the result
print(f"In 2050, you will be {age_in_2050} years old.")

